// Builds the single-file nesev executables (bun build --compile) and, with --package, the release assets.
//
//   bun scripts/build-binary.ts                       this machine's target, into build/bin/<target>/nesev
//   bun scripts/build-binary.ts --all --package       all release targets + build/release/ (tar.gz, SHA256SUMS, VERSION)
//   options: --targets darwin-arm64,linux-x64  --skip-web (reuse dist/web)  --require-helper (fail without the
//            prebuilt macOS OCR helper)
//
// Each binary embeds the files nesev reads at runtime (built SPA, migrations, fonts, the Swift OCR helper source and,
// for macOS, the helper compiled for that architecture) through a generated entry build/entry-<target>.ts; on start
// they're extracted to a cache dir that becomes APP_ROOT (src/cli/embedded.ts, src/server/lib/app-files.ts).

import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import pkg from "../package.json" with { type: "json" };

export const TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64"] as const;
type Target = (typeof TARGETS)[number];

const ROOT = resolve(import.meta.dir, "..");
const BUILD = join(ROOT, "build");
const OCR_SOURCE = "src/server/lib/ocr/nesev-ocr.swift";
// oldest macOS the prebuilt OCR helper runs on (Bun itself needs macOS 13+)
const MACOS_MIN = "13.0";

function sh(cmd: string[], opts: { cwd?: string } = {}) {
  const r = spawnSync(cmd[0]!, cmd.slice(1), { cwd: opts.cwd ?? ROOT, stdio: "inherit" });
  if (r.status !== 0) throw new Error(`failed: ${cmd.join(" ")}`);
}

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** Files relative to ROOT that every binary embeds. */
export function shippedFiles(): string[] {
  const rel = (p: string) => relative(ROOT, p);
  const migrations = join(ROOT, "src/server/db/migrations");
  return [
    ...walk(join(ROOT, "dist/web")).map(rel),
    ...readdirSync(migrations).filter((f) => f.endsWith(".sql")).map((f) => `src/server/db/migrations/${f}`),
    "src/server/db/migrations/meta/_journal.json",
    ...walk(join(ROOT, "src/server/assets/fonts")).map(rel),
    OCR_SOURCE,
  ].filter((f) => !f.endsWith(".DS_Store"));
}

/** Same name as lib/ocr/helper.ts uses: nesev-ocr-<first 12 hex digits of Bun.hash(source)> */
function helperName(): string {
  return `nesev-ocr-${Bun.hash(readFileSync(join(ROOT, OCR_SOURCE))).toString(16).padStart(16, "0").slice(0, 12)}`;
}

/** Compiles the OCR helper for a macOS target; null when that's impossible here (not macOS / no swiftc). */
function buildHelper(target: Target): string | null {
  if (process.platform !== "darwin" || !Bun.which("swiftc")) return null;
  const arch = target === "darwin-arm64" ? "arm64" : "x86_64";
  const out = join(BUILD, "helper", arch, helperName());
  if (existsSync(out)) return out;
  mkdirSync(join(BUILD, "helper", arch), { recursive: true });
  console.log(`swiftc ${arch} → ${relative(ROOT, out)}`);
  sh(["swiftc", "-O", "-target", `${arch}-apple-macos${MACOS_MIN}`, OCR_SOURCE, "-o", out]);
  return out;
}

function writeEntry(target: Target, files: [string, string][]): string {
  const spec = (abs: string) => (relative(BUILD, abs).startsWith("..") ? relative(BUILD, abs) : `./${relative(BUILD, abs)}`);
  const imports = files.map(([, abs], i) => `import f${i} from ${JSON.stringify(spec(abs))} with { type: "file" };`);
  const list = files.map(([rel], i) => `  [${JSON.stringify(rel)}, f${i}],`);
  const src = `// generated by scripts/build-binary.ts (${target}) – do not edit
import { extractEmbedded } from "../src/cli/embedded";
${imports.join("\n")}

const files = [
${list.join("\n")}
] as const;

try {
  process.env.NESEV_APP_ROOT = extractEmbedded(files, ${JSON.stringify(pkg.version)});
} catch (err) {
  console.error(\`nesev: could not extract its files: \${(err as Error).message}\`);
  process.exit(1);
}
process.env.NODE_ENV = "production";
const { run } = await import("../src/cli/main");
await run();
`;
  const file = join(BUILD, `entry-${target}.ts`);
  writeFileSync(file, src);
  return file;
}

function compile(target: Target, entry: string): string {
  const out = join(BUILD, "bin", target, "nesev");
  rmSync(join(BUILD, "bin", target), { recursive: true, force: true });
  sh([
    process.execPath,
    "build",
    "--compile",
    // x64: the baseline runtime runs on CPUs without AVX2 (older Intel Macs/PCs, Rosetta)
    `--target=bun-${target}${target.endsWith("-x64") ? "-baseline" : ""}`,
    "--define",
    'process.env.NODE_ENV="production"',
    "--minify-syntax",
    "--minify-whitespace",
    "--outfile",
    out,
    entry,
  ], { cwd: BUILD });
  // bun leaves a .<hash>.bun-build copy of its runtime in the working directory
  for (const f of readdirSync(BUILD)) if (f.endsWith(".bun-build")) rmSync(join(BUILD, f), { force: true });
  return out;
}

function packageTargets(targets: Target[]) {
  const out = join(BUILD, "release");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const sums: string[] = [];
  for (const target of targets) {
    const dir = join(BUILD, "bin", target);
    copyFileSync(join(ROOT, "LICENSE"), join(dir, "LICENSE"));
    const name = `nesev-${target}.tar.gz`;
    sh(["tar", "-czf", join(out, name), "-C", dir, "nesev", "LICENSE"]);
    sums.push(`${new Bun.CryptoHasher("sha256").update(readFileSync(join(out, name))).digest("hex")}  ${name}`);
  }
  writeFileSync(join(out, "SHA256SUMS"), `${sums.join("\n")}\n`);
  writeFileSync(join(out, "VERSION"), `${pkg.version}\n`);
  console.log(`\nRelease assets in ${relative(ROOT, out)}/:\n${readdirSync(out).map((f) => `  ${f}`).join("\n")}`);
}

function hostTarget(): Target {
  const t = `${process.platform}-${process.arch}`;
  if (!(TARGETS as readonly string[]).includes(t)) throw new Error(`no release target for ${t}`);
  return t as Target;
}

if (import.meta.main) {
  const argv = process.argv.slice(2);
  const flag = (n: string) => argv.includes(n);
  const ti = argv.indexOf("--targets");
  const targets: Target[] = flag("--all")
    ? [...TARGETS]
    : ti >= 0
      ? (argv[ti + 1] ?? "").split(",").map((t) => {
          if (!(TARGETS as readonly string[]).includes(t)) throw new Error(`unknown target ${t} (${TARGETS.join(", ")})`);
          return t as Target;
        })
      : [hostTarget()];

  if (!flag("--skip-web")) sh([process.execPath, "run", "build"]);
  if (!existsSync(join(ROOT, "dist/web/index.html"))) throw new Error("dist/web missing: run without --skip-web");

  const common: [string, string][] = shippedFiles().map((rel) => [rel, join(ROOT, rel)]);
  for (const target of targets) {
    const files = [...common];
    if (target.startsWith("darwin")) {
      const helper = buildHelper(target);
      if (helper) files.push([`bin/${helperName()}`, helper]);
      else if (flag("--require-helper")) throw new Error(`cannot build the OCR helper for ${target} (needs macOS + swiftc)`);
      else console.warn(`warning: ${target} without prebuilt OCR helper (compiled on first use with swiftc)`);
    }
    const bin = compile(target, writeEntry(target, files));
    console.log(`${target}: ${relative(ROOT, bin)} (${(statSync(bin).size / 1e6).toFixed(1)} MB, ${files.length} embedded files)`);
  }
  if (flag("--package")) packageTargets(targets);
}
